const bySlug = new Map(catalogue.map(about => [about.slug, about]))

export const aboutOf = (slug: string): Option.Option<About> =>
  Option.fromNullishOr(bySlug.get(slug))

/** The catalogue's entry for `slug`, for the module that draws it. */
export const about = (slug: string): About =>
  Option.getOrThrowWith(aboutOf(slug), () => new Error(`the catalogue has no ${slug}`))
