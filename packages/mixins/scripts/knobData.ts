/**
 * Writes `src/theme/knobData.ts` from `Knobs.standard`: `pnpm --filter foldkit-mixins generate:knob-data`.
 * The table is plain literals so a page that reads a few knobs loads no knob code;
 * `test/knobData.test.ts` fails when the committed file differs from `render()`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { format } from 'oxfmt'
import type { Knob } from '../src/theme/knob.js'
import { standard } from '../src/theme/knobs.js'
import type { KnobData } from '../src/theme/knobDataType.js'

const target = fileURLToPath(new URL('../src/theme/knobData.ts', import.meta.url))
// oxfmt's `format` discovers no config; this is the one `pnpm format` reads.
const { $schema: _, ...formatConfig } = JSON.parse(
  readFileSync(fileURLToPath(new URL('../../../.oxfmtrc.jsonc', import.meta.url)), 'utf8'),
)

const dataOf = (name: string, knob: Knob<unknown>): ReadonlyArray<KnobData> =>
  knob.control.kind === 'range' && typeof knob.default === 'number'
    ? [
        {
          name,
          title: knob.title,
          variable: knob.control.variable,
          unit: knob.control.unit,
          min: knob.control.min,
          max: knob.control.max,
          step: knob.control.step,
          default: knob.default,
        },
      ]
    : []

/** The range knobs of `Knobs.standard` in declaration order, a two-scheme knob as its two halves. */
export const entries = (): ReadonlyArray<KnobData> =>
  Object.entries(standard).flatMap(([group, knobs]) =>
    Object.entries(knobs).flatMap(([name, knob]) =>
      'light' in knob && 'dark' in knob
        ? [
            ...dataOf(`${group}.${name}.light`, knob.light),
            ...dataOf(`${group}.${name}.dark`, knob.dark),
          ]
        : dataOf(`${group}.${name}`, knob),
    ),
  )

/** `shape.density` as `shapeDensity`, an export a bundler can keep or drop on its own. */
const identifier = (name: string) =>
  name.replace(/\.(.)/g, (_, letter: string) => letter.toUpperCase())

/** The generated module's text, formatted as `pnpm format` would. */
export const render = async (): Promise<string> => {
  const all = entries()
  const identifiers = all.map(data => identifier(data.name))
  if (new Set(identifiers).size !== identifiers.length)
    throw new Error('two knobs have the same export name')
  const body = all
    .map(
      (data, index) =>
        `/** ${data.title}, \`--fk-knob-${data.variable}\`. */\n` +
        `export const ${identifiers[index]} = ${JSON.stringify(data)} as const satisfies KnobData<${JSON.stringify(data.name)}>`,
    )
    .join('\n\n')
  const table = all.map((data, index) => `${JSON.stringify(data.name)}: ${identifiers[index]},`)
  const source = `// Generated by \`pnpm --filter foldkit-mixins generate:knob-data\` from \`Knobs.standard\`. Do not edit.
import type { KnobData, RangeName } from './knobDataType.js'

export type { KnobData, RangeName }

${body}

/** Every range knob by path; a page that reads only some imports their exports instead. */
export const knobData = {
${table.join('\n')}
} as const satisfies { readonly [Name in RangeName]: KnobData<Name> }
`
  const { code } = await format(target, source, formatConfig)
  return code
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(target, await render())
